CREATE TABLE public.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name text NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 100 AND name = btrim(name))
);

CREATE TABLE public.tasks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 100 AND title = btrim(title)),
    completed boolean NOT NULL DEFAULT false,
    priority text NOT NULL CHECK (priority IN ('low', 'medium', 'high')),
    category_id integer NOT NULL REFERENCES public.categories (id) ON DELETE RESTRICT
);

CREATE INDEX tasks_category_id_idx ON public.tasks (category_id);
